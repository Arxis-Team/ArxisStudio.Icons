namespace ArxisStudio.Icons;

/// <summary>
/// Набор иконок студии: контурные пути в системе координат 16×16 для
/// <see cref="AxIcon"/>. Плагин может пользоваться этими же путями или дать свои.
/// </summary>
/// <remarks>
/// Путь разбирается при первом обращении к иконке, а не при загрузке типа: экрану нужны
/// единицы иконок из набора, и разбирать остальные до первого кадра незачем.
/// </remarks>
public static class AxIcons
{
    /// <summary>Пути набора, нарисованные силуэтом: их <see cref="AxIcon"/> заливает сам.</summary>
    private static readonly ConditionalWeakTable<Geometry, object> Silhouettes = new();

    /// <summary>Нарисован ли путь набора силуэтом, а не контуром.</summary>
    /// <param name="icon">Путь; чужой путь набору не принадлежит, и ответ для него — нет.</param>
    internal static bool IsFilled(Geometry? icon) => icon is not null && Silhouettes.TryGetValue(icon, out _);

    /// <summary>
    /// Клетки, в которых набор нарисован кроме основной шестнадцати.
    /// </summary>
    /// <remarks>
    /// Обычный значок в шестнадцать точек занимает при 125, 150 и 175 % ровно 20, 24 и 28 пикселей;
    /// мелкий, в двенадцать, — 12, 15, 18 и 21 при 100…175 %. При 200 % на единицу сетки приходится
    /// два пикселя, и путь клетки 16 ложится туда сам.
    /// </remarks>
    private static readonly int[] Cells = [12, 15, 18, 20, 21, 24, 28];

    /// <summary>Клетки, в которых набор нарисован кроме основной: их спрашивают проверки.</summary>
    internal static IReadOnlyList<int> Sizing => Cells;

    /// <summary>
    /// Пути этой иконки в клетках набора — строками, как их собрал генератор.
    /// </summary>
    /// <param name="icon">Путь набора.</param>
    /// <remarks>
    /// Проверкам нужен текст пути, а не разобранная геометрия: <c>ToString</c> у неё отдаёт запись
    /// Avalonia, с относительными командами, и сетку по ней не сверить.
    /// </remarks>
    internal static IReadOnlyList<string> Drawn(Geometry? icon) =>
        icon is not null && Sizes.TryGetValue(icon, out var sized) ? sized.Paths : [];

    /// <summary>Пересчёты путей под клетки набора.</summary>
    private static readonly ConditionalWeakTable<Geometry, Sized> Sizes = new();

    /// <summary>
    /// Путь этой иконки, нарисованный в клетке <paramref name="cell"/>; <c>null</c> — такой клетки
    /// у набора нет или путь не его.
    /// </summary>
    /// <param name="icon">Путь набора.</param>
    /// <param name="cell">Сторона клетки в единицах сетки.</param>
    /// <remarks>
    /// Набор нарисован в клетке 16, и в пиксели он ложится только там, где на единицу приходится
    /// целое их число: при 100 % это один пиксель, при 200 % — два. При 125, 150 и 175 % единица
    /// занимает 1.25, 1.5 и 1.75 пикселя, оси штрихов оказываются на четверти пикселя, и ядра у
    /// штриха не остаётся вовсе. Значок в шестнадцать точек занимает там ровно 20, 24 и 28
    /// пикселей — и путь, нарисованный в такой клетке, снова стоит на сетке.
    /// </remarks>
    internal static Geometry? Fitted(Geometry? icon, int cell) =>
        icon is not null && Sizes.TryGetValue(icon, out var sized) ? sized.Cell(cell) : null;

    private static Geometry P(string path) => Geometry.Parse(path);

    /// <summary>Путь клетки 16 и его пересчёты; разбирается тот, который сейчас нужен.</summary>
    private static Geometry P(string path, string[] fitted)
    {
        var icon = Geometry.Parse(path);

        Sizes.AddOrUpdate(icon, new Sized(fitted));

        return icon;
    }

    private static Geometry Filled(Geometry icon)
    {
        Silhouettes.AddOrUpdate(icon, icon);

        return icon;
    }

    /// <summary>Тот же рисунок в клетках набора: разбирается по первому спросу.</summary>
    private sealed class Sized(string[] paths)
    {
        private readonly Geometry?[] _parsed = new Geometry?[paths.Length];

        /// <summary>Пути как есть: их сверяют проверки набора.</summary>
        public IReadOnlyList<string> Paths => paths;

        public Geometry? Cell(int cell)
        {
            var at = Array.IndexOf(Cells, cell);

            return at < 0 ? null : _parsed[at] ??= Geometry.Parse(paths[at]);
        }
    }

